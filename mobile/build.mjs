// Build the installable file locally so mobile and Chrome ship the same feed and strict-mode logic.
import { readFile, writeFile } from 'node:fs/promises';
const read = path => readFile(new URL(path, import.meta.url), 'utf8');
const lib = name => read('../extension/' + name);
const source = name => read('src/' + name);
const icon = await readFile(new URL('../extension/icons/128.png', import.meta.url));
const catalogs = {};
for (const lang of ['en', 'es']) {
  const catalog = JSON.parse(await lib('_locales/' + lang + '/messages.json'));
  catalogs[lang] = Object.fromEntries(Object.entries(catalog).map(([key, value]) => [key, value.message]));
}
const css = (await Promise.all([lib('youtube.css'), lib('watch-panel.css'), source('mobile.css')])).join('\n');
const output = [
  await source('metadata.txt'),
  "// Generated by npm run build:mobile. Edit mobile/src or the shared extension sources.\n(() => {\n'use strict';",
  `if (window !== top || !['https://m.youtube.com', 'https://www.youtube.com', 'https://youtube.com'].includes(location.origin)) return;
const mounted = new WeakSet();
function start(window, embeddedPanel) {
  const {document, location, navigator, parent, top, performance,
    Element, HTMLAnchorElement, HTMLMediaElement, MutationObserver, ResizeObserver, BroadcastChannel} = window;
  if (mounted.has(document)) return;
  mounted.add(document);
  const requestAnimationFrame = window.requestAnimationFrame.bind(window);
  const cancelAnimationFrame = window.cancelAnimationFrame.bind(window);
  const getComputedStyle = window.getComputedStyle.bind(window);
  const matchMedia = window.matchMedia.bind(window);`,
  await source('landing.js'),
  await source('app-promotion.js'),
  'const messages = ' + JSON.stringify(catalogs, null, 2) + ';',
  await source('platform.js'),
  `StopItPlatform.mountPanel = frame => {
    const doc = frame.contentDocument;
    if (doc && doc.location.origin === location.origin && doc.location.pathname === '/feed/subscriptions')
      start(frame.contentWindow, true);
  };`,
  `const style = document.createElement('style');
style.textContent = ${JSON.stringify(css)} + (embeddedPanel ? ${JSON.stringify(await lib('panel-feed.css'))}.replace('__MSG_nowPlaying__', StopItPlatform.message('nowPlaying')) : '');
function mountStyle() {
  if (!document.documentElement) return;
  (document.head || document.documentElement).append(style);
  styleObserver.disconnect();
}
const styleObserver = new MutationObserver(mountStyle);
styleObserver.observe(document, {childList: true});
mountStyle();`,
  ...await Promise.all(['routes.js', 'metadata.js', 'strict-store.js', 'preferences.js', 'feed-dates.js',
    'strict-sections.js', 'strict-mode.js'].map(lib)),
  'if (embeddedPanel) {', await lib('panel-feed.js'), '} else {',
  await source('navigation.js'), await lib('youtube-controls.js'), await lib('settings.js'),
  `const stopItIcon = 'data:image/png;base64,${icon.toString('base64')}';`,
  await source('settings.js'), await lib('watch-panel.js'), '}',
  await lib('feed.js'), '}\nstart(window, false);\n})();\n'
].join('\n');
const target = new URL('stopit.user.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Rebuild mobile/stopit.user.js with npm run build:mobile.');
} else {
  await writeFile(target, output);
}
